export function pageSeo(path: string): PageSeo {
  const page = INDEXABLE_PAGES.find((p) => p.path === path);
  if (!page) throw new Error(`No SEO entry for ${path}; add it to INDEXABLE_PAGES in lib/site.ts`);
  return page;
}

const fullTitle = (title: string) => `${title} | ${SITE_NAME}`;

/** Title, description, canonical, Open Graph and Twitter metadata for one indexable page. */
export function pageMetadata(path: string): Metadata {
  const { title, description } = pageSeo(path);
  // The home page is the one place the brand name leads instead of trailing.
  const shown = path === '/' ? `${SITE_NAME} — ${title}` : fullTitle(title);
  const image = [{ url: OG_IMAGE.path, width: OG_IMAGE.width, height: OG_IMAGE.height, alt: OG_IMAGE.alt }];
  return {
    title: path === '/' ? { absolute: shown } : title,
    description,
    alternates: { canonical: path },
    openGraph: { type: 'website', siteName: SITE_NAME, title: shown, description, url: path, images: image },
    twitter: { card: 'summary_large_image', title: shown, description, images: [OG_IMAGE.path] },
  };
}

/** For areas that must stay out of search results: signed-in screens, reset links and share links. */
export const NOINDEX: Metadata = {
  robots: { index: false, follow: false, nocache: true },
  // The page address can carry a secret (a reset or share token): don't pass it on to other sites in the Referer header.
  referrer: 'no-referrer',
};

/**
 * Paths that must never be crawled or indexed. robots.txt asks well-behaved crawlers to stay out, and next.config.ts
 * also sends `X-Robots-Tag: noindex` for them — but neither is access control: those areas are protected by sign-in
 * or by an unguessable token.
 */
export const PRIVATE_PATH_PREFIXES = ['/admin', '/dashboard', '/portal', '/share', '/api'];

/** schema.org Organization for the home page. Only facts that are published on the site itself. */
export function organizationJsonLd() {
  return {
    '@context': 'https://schema.org',
    '@type': 'Organization',
    name: SITE_NAME,
    url: siteUrl(),
    logo: `${siteUrl()}/images/logo.png`,
    description: SITE_DESCRIPTION,
  };
}
