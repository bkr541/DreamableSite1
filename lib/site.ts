// One place for everything search engines and link previews are told about the public site: the canonical address
// (APP_URL), each indexable page's title/description, and which areas must never be indexed.
import type { Metadata, MetadataRoute } from 'next';

export const SITE_NAME = 'Dreamable.studio';
export const SITE_TAGLINE = 'A digital product and creative studio';
export const SITE_DESCRIPTION =
  'Dreamable.studio is a digital product and creative studio that turns ideas into structured brands, software, and systems that ship.';

/** Canonical origin of the deployed site, from APP_URL (no trailing slash). Falls back to localhost only outside production. */
export function siteUrl(): string {
  const raw = (process.env.APP_URL ?? '').trim().replace(/\/+$/, '');
  if (raw) {
    try {
      return new URL(raw).origin;
    } catch {
      /* a malformed value falls through to the default below */
    }
  }
  return 'http://localhost:3000';
}

/** Absolute URL for a path. The home page is the bare origin, matching the canonical link Next.js emits for "/". */
export const absoluteUrl = (path: string) => `${siteUrl()}${path === '/' ? '' : path}`;

/** The link-preview image. It is a real file in /public (generated by scripts/generate-brand-images.mjs). */
export const OG_IMAGE = { path: '/og.png', width: 1200, height: 630, alt: 'Dreamable.studio — a digital product and creative studio' };

export interface PageSeo {
  path: string;
  /** Page-specific part of the <title>; the root layout appends " | Dreamable.studio". */
  title: string;
  description: string;
  changeFrequency: NonNullable<MetadataRoute.Sitemap[number]['changeFrequency']>;
  priority: number;
}

